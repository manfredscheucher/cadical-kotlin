package org.bytefred.ksat.cadical.full

import kotlin.math.abs
import kotlin.math.min
import org.bytefred.ksat.cadical.IntArrayList

/*
 * compact.cpp: compacting the variable range (removing holes of inactive variables).
 *
 * Mapping notes:
 *  - 'template <class T> void map_vector (vector<T> &)' / 'map2_vector' -> one overload per
 *    table type. Primitive tables are reallocated with the new size, so those overloads
 *    return the new array ('parents = mapper.mapVector (parents)').
 *  - 'v[dst] = v[src]' on object tables (ftab, links, vtab, wtab, otab, big) moves the
 *    reference: since 'dst <= src' and the mapping is dense ('1..new_max_var' are hit exactly
 *    once, in increasing 'src' order), every slot of the result refers to a different
 *    object, so no two slots alias (same result as the C++ struct copies).
 *  - 'signed char *vals' with offset -> ByteArray indexed 'vsize + lit' (see InternalHpp.kt).
 *  - The shadow trace 'LSTRACE_PHASE ("compact")' -> [tracePhase] around 'compact'.
 */

/*------------------------------------------------------------------------*/

// Compacting removes holes generated by inactive variables (fixed,
// eliminated, substituted or pure) by mapping active variables indices down
// to a contiguous interval of indices.

/*------------------------------------------------------------------------*/

internal fun Internal.compacting(): Boolean {
    if (level != 0) return false
    if (opts.compact == 0) return false
    if (stats.conflicts < lim.compact) return false
    val inactive = maxVar - active()
    check(inactive >= 0)
    if (inactive == 0) return false
    if (inactive < opts.compactmin) return false
    return inactive >= (1e-3 * opts.compactlim) * maxVar
}

/*------------------------------------------------------------------------*/

private class Mapper(val internal: Internal) {

    var newMaxVar = 0 // New 'max_var' after compacting.
    val table: IntArray // Old variable index to new literal map.
    var firstFixed = 0 // First fixed variable index.
    var mapFirstFixed = 0 // Mapped literal of first fixed variable.
    var firstFixedVal = 0 // Value of first fixed variable (signed char).
    val newVsize: Int

    /*----------------------------------------------------------------------*/
    // We produce a compacting garbage collector like map of old 'src' to
    // new 'dst' variables.  Inactive variables are just skipped except for
    // fixed ones which will be mapped to the first fixed variable (in the
    // appropriate phase).  This avoids to handle the case 'fixed value'
    // separately as it is done in Lingeling, where fixed variables are
    // mapped to the internal variable '1'.
    //
    init {
        table = IntArray(internal.maxVar + 1)

        check(internal.level == 0)

        for (src in internal.vars) {
            val f = internal.flags(src)
            if (f.active()) {
                table[src] = ++newMaxVar
            } else if (f.fixed() && firstFixed == 0) {
                firstFixed = src
                mapFirstFixed = ++newMaxVar
                table[firstFixed] = mapFirstFixed
            }
        }

        firstFixedVal = if (firstFixed != 0) internal.value(firstFixed) else 0
        newVsize = newMaxVar + 1
    }

    /*----------------------------------------------------------------------*/
    // Map old variable indices.  A result of zero means not mapped.
    //
    fun mapIdx(src: Int): Int {
        check(0 < src)
        check(src <= internal.maxVar)
        val res = table[src]
        check(res <= newMaxVar)
        return res
    }

    /*----------------------------------------------------------------------*/
    // The 'map_idx' above is just a look-up into the 'table'.  Here we have
    // to care about signedness of 'src', and in addition that fixed variables
    // have all to be mapped to the first fixed variable 'first_fixed'.
    //
    fun mapLit(src: Int): Int {
        var res = mapIdx(abs(src))
        if (res == 0) {
            val tmp = internal.value(src)
            if (tmp != 0) {
                check(firstFixed != 0)
                res = mapFirstFixed
                if (tmp != firstFixedVal) res = -res
            }
        } else if ((src) < 0) {
            res = -res
        }
        check(abs(res) <= newMaxVar)
        return res
    }

    /*----------------------------------------------------------------------*/
    // Map positive variable indices in vector.
    //
    fun <T> mapVector(v: MutableList<T>) {
        for (src in internal.vars) {
            val dst = mapIdx(src)
            if (dst == 0) continue
            check(0 < dst)
            check(dst <= src)
            v[dst] = v[src]
        }
        v.shrinkTo(newVsize)
        // shrink_vector (v)
    }

    fun mapVector(v: IntArrayList) {
        for (src in internal.vars) {
            val dst = mapIdx(src)
            if (dst == 0) continue
            check(0 < dst)
            check(dst <= src)
            v[dst] = v[src]
        }
        v.resize(newVsize)
        // shrink_vector (v)
    }

    fun mapVector(v: IntArray): IntArray {
        for (src in internal.vars) {
            val dst = mapIdx(src)
            if (dst == 0) continue
            check(0 < dst)
            check(dst <= src)
            v[dst] = v[src]
        }
        return v.resized(newVsize)
    }

    fun mapVector(v: ByteArray): ByteArray {
        for (src in internal.vars) {
            val dst = mapIdx(src)
            if (dst == 0) continue
            check(0 < dst)
            check(dst <= src)
            v[dst] = v[src]
        }
        return v.resized(newVsize)
    }

    fun mapVector(v: LongArray): LongArray {
        for (src in internal.vars) {
            val dst = mapIdx(src)
            if (dst == 0) continue
            check(0 < dst)
            check(dst <= src)
            v[dst] = v[src]
        }
        return v.resized(newVsize)
    }

    fun mapVector(v: DoubleArray): DoubleArray {
        for (src in internal.vars) {
            val dst = mapIdx(src)
            if (dst == 0) continue
            check(0 < dst)
            check(dst <= src)
            v[dst] = v[src]
        }
        return v.resized(newVsize)
    }

    /*----------------------------------------------------------------------*/
    // Map positive and negative variable indices in two-sided vector.
    //
    fun <T> map2Vector(v: MutableList<T>) {
        for (src in internal.vars) {
            val dst = mapIdx(src)
            if (dst == 0) continue
            check(0 < dst)
            check(dst <= src)
            v[2 * dst] = v[2 * src]
            v[2 * dst + 1] = v[2 * src + 1]
        }
        v.shrinkTo(2 * newVsize)
        // shrink_vector (v)
    }

    fun map2Vector(v: IntArray): IntArray {
        for (src in internal.vars) {
            val dst = mapIdx(src)
            if (dst == 0) continue
            check(0 < dst)
            check(dst <= src)
            v[2 * dst] = v[2 * src]
            v[2 * dst + 1] = v[2 * src + 1]
        }
        return v.resized(2 * newVsize)
    }

    fun map2Vector(v: LongArray): LongArray {
        for (src in internal.vars) {
            val dst = mapIdx(src)
            if (dst == 0) continue
            check(0 < dst)
            check(dst <= src)
            v[2 * dst] = v[2 * src]
            v[2 * dst + 1] = v[2 * src + 1]
        }
        return v.resized(2 * newVsize)
    }

    /*----------------------------------------------------------------------*/
    // Map a vector of literals, flush inactive literals, then resize and
    // shrink it to fit the new size after flushing.
    //
    fun mapFlushAndShrinkLits(v: IntArrayList) {
        val end = v.size
        var j = 0
        for (i in 0 until end) {
            val src = v[i]
            var dst = mapIdx(abs(src))
            check(abs(dst) <= abs(src))
            if (dst == 0) continue
            if (src < 0) dst = -dst
            v[j++] = dst
        }
        v.resize(j)
        // shrink_vector (v)
    }
}

/*------------------------------------------------------------------------*/

internal fun Internal.compact() {
    tracePhase("compact") {

        check(active() < maxVar)

        stats.compacts++

        check(level == 0)
        check(!unsat)
        check(conflict == null)
        check(clause.isEmpty())
        check(levels.isEmpty())
        check(analyzed.isEmpty())
        check(minimized.isEmpty())
        check(control.size == 1)
        check(propagated == trail.size)

        garbageCollection()

        val mapper = Mapper(this)

        // LOG: found first fixed / no variable fixed

        val ext = external!!

        if (!assumptions.isEmpty()) {
            check(!ext.assumptions.isEmpty())
            // LOG: temporarily reset internal assumptions
            resetAssumptions()
        }

        val isConstraint = !constraint.isEmpty()
        if (isConstraint) {
            check(!ext.constraint.isEmpty())
            // LOG: temporarily reset internal constraint
            resetConstraint()
        }

        /*======================================================================*/
        // In this first part we only map stuff without reallocation / shrinking.
        /*======================================================================*/

        // Flush the external indices.  This has to occur before we map 'vals'.
        // Also fixes external units.
        //
        for (eidx in ext.vars) {
            val src = ext.e2i[eidx]
            if (src == 0) {
                continue
            }
            if (lrat || frat) {
                check(eidx > 0)
                check(ext.extUnits.size >= 2 * eidx + 1)
                val id1 = ext.extUnits[2 * eidx]
                val id2 = ext.extUnits[2 * eidx + 1]
                check(id1 == 0L || id2 == 0L)
                if (id1 == 0L && id2 == 0L) {
                    val newId1 = unitClauses(2 * src)
                    val newId2 = unitClauses(2 * src + 1)
                    ext.extUnits[2 * eidx] = newId1
                    ext.extUnits[2 * eidx + 1] = newId2
                }
            }
            val dst = mapper.mapLit(src)
            // LOG: compact maps external eidx to internal dst from internal src
            ext.e2i[eidx] = dst
        }

        // Delete garbage units. Needs to occur before resizing unit_clauses
        //
        if (lrat || frat) {
            for (src in vars) {
                val dst = mapper.mapIdx(src)
                check(dst <= src)
                val tmp = value(src)
                if (dst == 0 && tmp == 0) {
                    unitClausesIdx[2 * src] = 0
                    unitClausesIdx[2 * src + 1] = 0
                    continue
                }
                if (tmp == 0 || src == mapper.firstFixed) {
                    check(0 < dst)
                    if (dst == src) continue
                    check(unitClauses(2 * dst) == 0L && unitClauses(2 * dst + 1) == 0L)
                    unitClausesIdx[2 * dst] = unitClauses(2 * src)
                    unitClausesIdx[2 * dst + 1] = unitClauses(2 * src + 1)
                    unitClausesIdx[2 * src] = 0
                    unitClausesIdx[2 * src + 1] = 0
                    continue
                }
                var id = unitClauses(2 * src)
                var lit = src
                if (id == 0L) {
                    id = unitClauses(2 * src + 1)
                    lit = -lit
                }
                unitClausesIdx[2 * src] = 0
                unitClausesIdx[2 * src + 1] = 0
                check(id != 0L)
            }
            unitClausesIdx = unitClausesIdx.resized(2 * mapper.newVsize)
            // shrink_vector (unit_clauses_idx)
        }
        // Map the literals in all clauses.
        //
        for (c in clauses) {
            check(!c.garbage)
            for (k in 0 until c.size) {
                val src = c.literals[k]
                check(value(src) == 0)
                val dst: Int
                dst = mapper.mapLit(src)
                check(dst != 0 || c.garbage)
                c.literals[k] = dst
            }
        }

        // Map the blocking literals in all watches.
        //
        if (wtab.isNotEmpty()) {
            for (lit in lits) {
                for (w in watches(lit)) w.blit = mapper.mapLit(w.blit)
            }
        }

        // We first flush inactive variables and map the links in the queue.  This
        // has to be done before we map the actual links data structure 'links'.
        run {
            var prev = 0
            var mappedPrev = 0
            var next: Int
            var idx = queue.first
            while (idx != 0) {
                next = links[idx].next
                if (idx == mapper.firstFixed) {
                    idx = next
                    continue
                }
                val dst = mapper.mapIdx(idx)
                if (dst == 0) {
                    idx = next
                    continue
                }
                check(active(idx))
                if (prev != 0) links[prev].next = dst
                else queue.first = dst
                links[idx].prev = mappedPrev
                mappedPrev = dst
                prev = idx
                idx = next
            }
            if (prev != 0) links[prev].next = 0
            else queue.first = 0
            queue.last = mappedPrev
            queue.unassigned = queue.last
        }

        /*======================================================================*/
        // In the second part we map, flush and shrink arrays.
        /*======================================================================*/

        check(trail.size == numAssigned)
        mapper.mapFlushAndShrinkLits(trail)
        propagated = trail.size
        numAssigned = trail.size
        if (mapper.firstFixed != 0) {
            check(trail.size == 1)
            variable(mapper.firstFixed).trail = 0 // before mapping 'vtab'
        } else {
            check(trail.isEmpty())
        }

        if (!probes.isEmpty()) mapper.mapFlushAndShrinkLits(probes)

        /*======================================================================*/
        // In the third part we map stuff and also reallocate memory.
        /*======================================================================*/

        // Now we continue in reverse order of allocated bytes, e.g., see
        // 'Internal::enlarge' which reallocates in order of allocated bytes.

        mapper.mapVector(ftab)
        parents = mapper.mapVector(parents)
        marks = mapper.mapVector(marks)
        phases.saved = mapper.mapVector(phases.saved)
        phases.forced = mapper.mapVector(phases.forced)
        phases.target = mapper.mapVector(phases.target)
        phases.best = mapper.mapVector(phases.best)
        phases.prev = mapper.mapVector(phases.prev)
        phases.min = mapper.mapVector(phases.min)

        // Special code for 'frozentab'.
        //
        for (src in vars) {
            val dst = abs(mapper.mapLit(src))
            if (dst == 0) continue
            if (src == dst) continue
            check(dst < src)
            if (src >= frozentab.size) break
            if (dst >= frozentab.size) break
            frozentab[dst] += frozentab[src]
            frozentab[src] = 0
        }
        frozentab = frozentab.resized(min(frozentab.size, mapper.newVsize))
        // shrink_vector (frozentab)

        // Special code for 'relevanttab'.
        //
        if (external != null) {
            for (src in vars) {
                val dst = abs(mapper.mapLit(src))
                if (dst == 0) continue
                if (src == dst) continue
                check(dst < src)

                relevanttab[dst] += relevanttab[src]
                relevanttab[src] = 0
            }
            relevanttab = relevanttab.resized(mapper.newVsize)
            // shrink_vector (relevanttab)
        }

        /*----------------------------------------------------------------------*/

        if (!ext.assumptions.isEmpty()) {

            for (k in 0 until ext.assumptions.size) {
                val elit = ext.assumptions[k]
                check(elit != 0)
                check(elit != Int.MIN_VALUE)
                val eidx = abs(elit)
                check(eidx <= ext.maxVar)
                var ilit = ext.e2i[eidx]
                check(ilit != 0) // Because we froze all!!!
                if (elit < 0) ilit = -ilit
                assume(ilit)
            }

            // PHASE: reassumed external assumptions
        }

        // Special case for 'val' as for 'val' we trade branch less code for
        // memory and always allocated an [-maxvar,...,maxvar] array.
        run {
            val newVals = ByteArray(2 * mapper.newVsize)
            val off = mapper.newVsize // 'new_vals += mapper.new_vsize'
            for (src in vars) newVals[off - mapper.mapIdx(src)] = vals[vsize - src]
            for (src in vars) newVals[off + mapper.mapIdx(src)] = vals[vsize + src]
            newVals[off + 0] = 0
            vals = newVals
            vsize = mapper.newVsize
        }

        // 'constrain' uses 'val', so this code has to be after remapping that
        if (isConstraint) {
            check(level == 0)
            check(ext.constraint.back() == 0)
            for (k in 0 until ext.constraint.size) {
                val elit = ext.constraint[k]
                check(elit != Int.MIN_VALUE)
                val eidx = abs(elit)
                check(eidx <= ext.maxVar)
                var ilit = ext.e2i[eidx]
                check((ilit == 0) == (elit == 0))
                if (elit < 0) ilit = -ilit
                // LOG: re adding lit to constraint
                constrain(ilit)
            }
            // PHASE: added external literals to constraint
        }

        mapper.mapVector(i2e)
        ptab = mapper.map2Vector(ptab)
        btab = mapper.mapVector(btab)
        gtab = mapper.mapVector(gtab)
        mapper.mapVector(links)
        mapper.mapVector(vtab)
        if (ntab.isNotEmpty()) ntab = mapper.map2Vector(ntab)
        if (wtab.isNotEmpty()) mapper.map2Vector(wtab)
        if (otab.isNotEmpty()) mapper.map2Vector(otab)
        if (big.isNotEmpty()) mapper.map2Vector(big)

        /*======================================================================*/
        // In the fourth part we map the binary heap for scores.
        /*======================================================================*/

        // The simplest way to map a binary heap is to get all elements from the
        // heap and reinsert them.  This could be slightly improved in terms of
        // speed if we add a 'flush (int * map)' function to 'Heap', but that is
        // pretty complicated and would require that the 'Heap' knows that mapped
        // elements with 'zero' destination should be flushed.

        val saved = IntArrayList()
        check(saved.isEmpty())
        if (!scores.empty()) {
            while (!scores.empty()) {
                val src = scores.front()
                scores.popFront()
                val dst = mapper.mapIdx(src)
                if (dst == 0) continue
                if (src == mapper.firstFixed) continue
                saved.add(dst)
            }
            scores.erase()
        }
        stab = mapper.mapVector(stab)
        if (!saved.isEmpty()) {
            for (k in 0 until saved.size) scores.pushBack(saved[k])
            scores.shrink()
        }

        /*----------------------------------------------------------------------*/

        // PHASE: reducing internal variables

        /*----------------------------------------------------------------------*/

        // Need to adjust the target and best assigned counters too.

        var newTargetAssigned = 0
        var newBestAssigned = 0

        for (idx in Range { mapper.newMaxVar }) {
            if (phases.target[idx].toInt() != 0) newTargetAssigned++
            if (phases.best[idx].toInt() != 0) newBestAssigned++
        }

        // LOG: reset target / best assigned

        targetAssigned = newTargetAssigned
        bestAssigned = newBestAssigned
        noConflictUntil = 0
        notified = 0

        initEma(averages.current.trail.fast, opts.ematrailfast)
        initEma(averages.current.trail.slow, opts.ematrailslow)

        /*----------------------------------------------------------------------*/

        maxVar = mapper.newMaxVar

        stats.unused = 0
        stats.now.fixed = if (mapper.firstFixed != 0) 1L else 0L
        stats.inactive = stats.now.fixed
        stats.now.pure = 0
        stats.now.eliminated = stats.now.pure
        stats.now.substituted = stats.now.eliminated

        checkVarStats()

        val delta: Long = opts.compactint * (stats.compacts + 1)
        lim.compact = stats.conflicts + delta

        // PHASE: new compact limit
    }
}
